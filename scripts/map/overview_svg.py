"""Writes src/assets/germanyShapes.ts: Germany and its 16 states as SVG paths for the Overview map.

Boundaries from VG1000 (BKG), land areas only (GF = 4), simplified in EPSG:25832 (metres) and drawn in
that projection, so shapes keep their proportions. Small enough to inline in the app: no basemap or
request needed, and it works offline.

Source: © GeoBasis-DE / BKG, VG1000 (dl-de/by-2-0). Modified: simplified and converted to SVG paths.

Usage: python -I scripts/map/overview_svg.py <DE_VG1000.gpkg>
Needs shapely.
"""
import json
import os
import sqlite3
import sys

from shapely import wkb
from shapely.geometry import MultiPolygon, Polygon
from shapely.ops import unary_union

gpkg = sys.argv[1]
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "src", "assets", "germanyShapes.ts")
WIDTH = 600          # viewBox width; height follows the shape
TOLERANCE = 1500     # metres
MIN_AREA = 4e6       # drop islands under 4 km² at this scale


def geom(blob):
    env = {0: 0, 1: 32, 2: 48, 3: 48, 4: 64}[(blob[3] >> 1) & 0b111]
    return wkb.loads(bytes(blob[8 + env:]))


con = sqlite3.connect(gpkg)
country = unary_union([geom(r[0]) for r in con.execute("SELECT geom FROM vg1000_sta WHERE GF = 4")])
states = [(r[0][:2], r[1], geom(r[2])) for r in con.execute("SELECT AGS, GEN, geom FROM vg1000_lan WHERE GF = 4 ORDER BY AGS")]

minx, miny, maxx, maxy = country.bounds
scale = WIDTH / (maxx - minx)
height = round((maxy - miny) * scale)


def polygons(g):
    g = g.simplify(TOLERANCE, preserve_topology=True)
    parts = list(g.geoms) if isinstance(g, MultiPolygon) else [g] if isinstance(g, Polygon) else []
    return [p for p in parts if p.area >= MIN_AREA]


def ring(coords):
    pts = [f"{(x - minx) * scale:.1f},{(maxy - y) * scale:.1f}" for x, y in coords]
    return "M" + "L".join(pts[:-1]) + "Z"


def path(g):
    return "".join(ring(p.exterior.coords) + "".join(ring(i.coords) for i in p.interiors) for p in polygons(g))


out = {
    "viewBox": f"0 0 {WIDTH} {height}",
    "country": path(country),
    "states": [{"ags": a, "name": n, "d": path(g)} for a, n, g in states],
}
os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, "w", encoding="utf-8") as f:
    f.write("// Generated by scripts/map/overview_svg.py from VG1000 (© GeoBasis-DE / BKG, dl-de/by-2-0). Don't edit.\n")
    f.write("export interface StateShape {\n  ags: string;\n  name: string;\n  d: string;\n}\n\n")
    f.write(f"export const GERMANY_VIEWBOX = {json.dumps(out['viewBox'])};\n\n")
    f.write(f"export const GERMANY_PATH = {json.dumps(out['country'])};\n\n")
    f.write("export const STATE_SHAPES: readonly StateShape[] = " + json.dumps(out["states"], ensure_ascii=False, indent=2) + ";\n")
print(f"{OUT}: {os.path.getsize(OUT) / 1000:.1f} kB, viewBox {out['viewBox']}, {len(out['states'])} states")
